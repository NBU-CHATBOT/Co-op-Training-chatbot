function answer(question) {

    let reply = "";

    if (question === "تعريف التدريب التعاوني") {
        reply = "التدريب التعاوني هو برنامج تدريبي يهدف إلى تأهيل الطلاب عمليًا قبل التخرج من خلال تطبيق المعرفة النظرية في بيئة العمل واكتساب المهارات المهنية اللازمة لسوق العمل.";
    }

    else if (question === "أهمية التدريب التعاوني") {
        reply = "يساعد التدريب التعاوني على: ربط الدراسة النظرية بالتطبيق العملي، تطوير مهارات الطلاب المهنية والشخصية، إعداد الطلاب لسوق العمل، واكتساب خبرة عملية قبل التخرج.";
    }

    else if (question === "أهداف التدريب التعاوني") {
        reply = "من أهم أهداف التدريب: تنمية المهارات العملية لدى الطلاب، تعزيز المعرفة التخصصية والتطبيق العملي، تدريب الطلاب على تحمل المسؤولية والالتزام، تطوير مهارات التواصل والعمل الجماعي، إكساب الطلاب مهارات التخطيط والتنفيذ، استخدام التقنيات الحديثة في العمل، وتعزيز التعاون بين الجامعة وسوق العمل.";
    }

    else if (question === "جهة التدريب") {
        reply = "مؤسسة حكومية أو خاصة معتمدة يتم فيها تدريب الطالب بما يتناسب مع تخصصه.";
    }

    else if (question === "المتدرب") {
        reply = "هو الطالب الذي استوفى شروط التدريب وتم قبوله في البرنامج.";
    }

    else if (question === "المشرف الميداني") {
        reply = "موظف من جهة التدريب يشرف على الطالب أثناء فترة التدريب ويتابع أداءه ومهامه التدريبية.";
    }

    else if (question === "المشرف الأكاديمي") {
        reply = "عضو هيئة تدريس من الجامعة يتابع الطالب ويقيم أداءه خلال فترة التدريب.";
    }

    else if (question === "خطة التدريب") {
        reply = "برنامج يتم الاتفاق عليه بين الجامعة وجهة التدريب، ويحدد مهام الطالب التدريبية والمهارات التي يجب اكتسابها.";
    }

    else if (question === "مدة التدريب التعاوني") {
        reply = "بالعادة 8 أسابيع تقريبًا بما يعادل 240 ساعة تدريبية.";
    }

    else if (question === "مراحل التدريب التعاوني") {
        reply = "يمر التدريب التعاوني بثلاث مراحل رئيسية: مرحلة الإعداد، مرحلة تنفيذ التدريب، ومرحلة التقييم.";
    }

    else if (question === "مرحلة الاعداد") {
        reply = "تشمل مرحلة الإعداد: تحديد الطلاب المؤهلين للتدريب، توفير جهات التدريب المناسبة، عقد لقاءات تعريفية للطلاب، وتحديد المشرفين الأكاديميين.";
    }

    else if (question === "مرحلة تنفيذ التدريب") {
        reply = "تشمل بدء الطالب التدريب في جهة التدريب، متابعة الطالب من قبل المشرف الميداني، متابعة الطالب من قبل المشرف الأكاديمي، وتقديم التقارير الدورية عن التدريب.";
    }

    else if (question === "مرحلة التقييم") {
        reply = "بعد انتهاء التدريب يتم تسليم تقارير التدريب، تقييم أداء الطالب، مناقشة تقرير التدريب، ورصد الدرجات النهائية.";
    }

    else if (question === "مهام مكتب التدريب التعاوني") {
        reply = "من أهم مهامه: توزيع الطلاب على جهات التدريب، توفير فرص تدريب مناسبة، التنسيق بين الأقسام وجهات التدريب، متابعة تنفيذ التدريب، جمع تقارير التقييم، وتطوير برنامج التدريب التعاوني.";
    }

    else if (question === "مهام جهة التدريب") {
        reply = "تشمل: تعريف الطالب ببيئة العمل، تدريب الطالب على المهام المهنية، متابعة أداء الطالب، تسجيل الحضور والانصراف، تقييم أداء الطالب، والتواصل مع المشرف الأكاديمي.";
    }

    else if (question === "شروط الالتحاق بالتدريب") {
        reply = "من أهم الشروط: أن يكون الطالب منتظمًا أكاديميًا، أن يكون متفرغًا للتدريب خلال فترة التدريب، اجتياز عدد معين من الساعات الدراسية، والالتزام بأنظمة التدريب.";
    }

    else if (question === "مسؤوليات الطالب المتدرب") {
        reply = "يجب على الطالب الالتزام بالحضور في مواعيد التدريب، اتباع أنظمة جهة التدريب، حضور الاجتماعات واللقاءات التدريبية، تقديم التقارير المطلوبة، الاستفادة من توجيهات المشرفين، وتقديم عرض عن تجربة التدريب بعد الانتهاء.";
    }

    else if (question === "تقييم التدريب التعاوني") {
        reply = "يتم تقييم الطالب بناءً على تقييم جهة التدريب، تقييم المشرف الأكاديمي، تقرير التدريب النهائي، وعرض ومناقشة التقرير. المجموع النهائي عادة 100 درجة.";
    }

    else if (question === "تقرير التدريب التعاوني") {
        reply = "يجب أن يحتوي التقرير على: صفحة الغلاف، الشكر والتقدير، جدول المحتويات، مقدمة عن جهة التدريب، وصف المهام التي قام بها الطالب، المهارات المكتسبة، النتائج والتوصيات. ويجب أن يكون منظمًا وواضحًا ومكتوبًا باللغة الإنجليزية ولا يقل عن 10 صفحات تقريبًا.";
    }

    else {
        reply = "آسف، لا أستطيع تقديم المعلومات المطلوبة.";
    }

    return reply;
}


/* إظهار الإجابة عند الضغط على السؤال */

function showAnswer(question) {

    let chatbox = document.getElementById("chatbox");

    let response = answer(question);

    // إضافة السؤال للمحادثة
    chatbox.innerHTML += `
        <div class="user-message">
            ${question}
        </div>
    `;

    // إضافة الإجابة
    chatbox.innerHTML += `
        <div class="bot-message">
            ${response}
        </div>
    `;

    // النزول لآخر المحادثة
    chatbox.scrollTop = chatbox.scrollHeight;
}


/* إرسال سؤال من خانة الكتابة */

function sendMessage() {

    let input = document.getElementById("userInput");

    let question = input.value.trim();

    if (question === "") {
        return;
    }

    let matchedQuestion = findQuestion(question);

    showAnswer(matchedQuestion);

    input.value = "";
}


/* البحث عن السؤال الأقرب */

function findQuestion(text) {

    text = text.trim();

    if (
        text.includes("تعريف") ||
        text.includes("وش هو التدريب") ||
        text.includes("ما هو التدريب")
    ) {
        return "تعريف التدريب التعاوني";
    }

    if (
        text.includes("أهمية") ||
        text.includes("ليش التدريب مهم")
    ) {
        return "أهمية التدريب التعاوني";
    }

    if (
        text.includes("أهداف") ||
        text.includes("هدف التدريب")
    ) {
        return "أهداف التدريب التعاوني";
    }

    if (text.includes("جهة التدريب")) {
        return "جهة التدريب";
    }

    if (text.includes("المتدرب")) {
        return "المتدرب";
    }

    if (text.includes("المشرف الميداني")) {
        return "المشرف الميداني";
    }

    if (text.includes("المشرف الأكاديمي")) {
        return "المشرف الأكاديمي";
    }

    if (text.includes("خطة التدريب")) {
        return "خطة التدريب";
    }

    if (text.includes("مدة التدريب")) {
        return "مدة التدريب التعاوني";
    }

    if (text.includes("مراحل التدريب")) {
        return "مراحل التدريب التعاوني";
    }

    if (text.includes("الإعداد") || text.includes("الاعداد")) {
        return "مرحلة الاعداد";
    }

    if (text.includes("تنفيذ التدريب")) {
        return "مرحلة تنفيذ التدريب";
    }

    if (text.includes("التقييم")) {
        return "مرحلة التقييم";
    }

    if (text.includes("مكتب التدريب")) {
        return "مهام مكتب التدريب التعاوني";
    }

    if (text.includes("مهام جهة")) {
        return "مهام جهة التدريب";
    }

    if (
        text.includes("شروط") ||
        text.includes("الالتحاق")
    ) {
        return "شروط الالتحاق بالتدريب";
    }

    if (
        text.includes("مسؤوليات الطالب") ||
        text.includes("مسؤوليات المتدرب")
    ) {
        return "مسؤوليات الطالب المتدرب";
    }

    if (
        text.includes("تقييم التدريب") ||
        text.includes("كيف يتم التقييم")
    ) {
        return "تقييم التدريب التعاوني";
    }

    if (
        text.includes("تقرير التدريب") ||
        text.includes("التقرير")
    ) {
        return "تقرير التدريب التعاوني";
    }

    return text;
}


